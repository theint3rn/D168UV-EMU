#!/usr/bin/env python3
"""Run D168UV firmware (Artery AT32F403A) in Renode, headless.

  emu/run.py --seconds 3                        # stock V1.07 image
  emu/run.py --elf ../cfw/build/cfw168.elf      # custom firmware
  emu/run.py --serve 1335 --seconds 5           # keep running, monitor on telnet :1335 (drive with ctl.py)
  emu/run.py --trace-periph                     # log every peripheral access (slow)

Output in emu/out/<name>/: renode.log, run.resc, state.txt, lcd.png, uart*.txt.
"""
import argparse, glob, os, re, shutil, subprocess, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RENODE = os.environ.get("RENODE", os.path.expanduser("~/.local/opt/renode_1.17.0-portable/renode"))
STOCK = os.path.join(ROOT, "fw", "d168uv_v107_08004000.bin")
UARTS = ["usart1", "usart2", "usart3", "usart4", "usart5"]
CFW_MODELS_CS = ["Analog168.cs", "Dac168.cs", "Pwm168.cs", "SymbolSource.cs", "PcmTap.cs"]   # --cfw overlay (cfw168.repl)
MODELS_CS = ["LcdKeypad.cs", "SpiNand168.cs", "BoardInputs168.cs", "RfTransceiver.cs", "Baseband168.cs", "I2cBus168.cs", "Knob168.cs", "Rtc168.cs",
             "Bt168.cs", "Gps168.cs"]
STOCK_MODELS_CS = ["Analog168.cs"]                    # stock overlay (stock168.repl): ADC1 battery scan


def fmt_time(s):
    return "%d:%02d:%09.6f" % (s // 3600, (s % 3600) // 60, s % 60) if s >= 60 else "%.6f" % s


def elf_syms(path):
    out = subprocess.check_output(["arm-none-eabi-nm", path], text=True)
    return {l.split()[2]: int(l.split()[0], 16) for l in out.splitlines() if len(l.split()) == 3}


def default_nand(stock=False):
    """images/extflash.pages (built from the user's own AnyTone package) if present, else images/synth.pages
    (our own synthetic image, generated by make_nand.py when missing). EMU_NO_ANYTONE=1 in the environment ignores
    extflash.pages, as on a fresh clone of the published repo (test runs: cfw/tools/*_test.py)."""
    ext = os.path.join(HERE, "images", "extflash.pages")
    if os.path.exists(ext) and not os.environ.get("EMU_NO_ANYTONE"):
        return ext
    synth = os.path.join(HERE, "images", "synth.pages")
    if not os.path.exists(synth):
        subprocess.check_call([sys.executable, os.path.join(HERE, "make_nand.py"), "--out", synth])
    if stock:
        print("note: images/extflash.pages not found, stock firmware runs on images/synth.pages "
              "(no ICON fonts/logo); see emu/README.md \"Images\"")
    return synth


def make_platform(out, systick=None, nand=None):
    src = open(os.path.join(HERE, "at32f403a.repl")).read()
    if nand:
        src = src.replace('"IMAGES/extflash.pages"', '"%s"' % os.path.abspath(nand))
    if systick:                                  # e.g. cfw: SysTick = HCLK/8 = 15 MHz (stock FUN_08013c64 too)
        src = re.sub(r"systickFrequency: \d+", "systickFrequency: %d" % systick, src)
    src = src.replace('"MODELS/', '"%s/' % os.path.join(HERE, "models"))
    src = src.replace('"IMAGES/', '"%s/' % os.path.join(HERE, "images"))
    dst = os.path.join(out, "platform.repl")
    open(dst, "w").write(src)
    return dst


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--elf", help="ELF to load instead of the stock image")
    ap.add_argument("--image", help="flat image loaded at 0x08004000 (default: stock V1.07)")
    ap.add_argument("--seconds", type=float, default=2.0)
    ap.add_argument("--name")
    ap.add_argument("--trace-periph", action="store_true")
    ap.add_argument("--extra", action="append", default=[])
    ap.add_argument("--then", action="append", default=[], help='"SECONDS|monitor command"; "shot" = screenshot')
    ap.add_argument("--serve", type=int, default=0)
    ap.add_argument("--gdb", type=int)
    ap.add_argument("--samples", type=int, default=0)
    ap.add_argument("--timeout", type=int, default=900)
    ap.add_argument("--exact", action="store_true", help="no speedups")
    ap.add_argument("--cfw", action="store_true",
                    help="custom firmware: cfw168.repl overlay (ADC/DAC/flash/syms/pcm), D168 keypad map, SysTick 15 MHz")
    ap.add_argument("--uart-socket", action="append", default=[], help="e.g. usart1:3480 (CPS link over TCP)")
    ap.add_argument("--nand", help="NAND pages file (default images/extflash.pages if present, else images/synth.pages "
                                   "from make_nand.py)")
    ap.add_argument("--systick", type=int, help="override nvic systickFrequency (cfw: 15000000 = HCLK/8)")
    a = ap.parse_args()
    name = a.name or (os.path.splitext(os.path.basename(a.elf))[0] if a.elf else "stock")
    out = os.path.join(HERE, "out", name)
    os.makedirs(out, exist_ok=True)
    for f in os.listdir(out):                        # no stale shots from an earlier run
        if re.match(r"lcd_\d+\.(ppm|png)$", f):
            os.remove(os.path.join(out, f))
    for f in glob.glob(os.path.join(out, "*.txt")) + glob.glob(os.path.join(out, "*.ppm")):
        os.remove(f)
    if a.elf:
        img = os.path.join(out, "fw.elf"); shutil.copyfile(a.elf, img)
        load = ["sysbus LoadELF @%s" % img]
    else:
        if not a.image and not os.path.exists(STOCK):
            sys.exit("stock run needs the V1.07 firmware image made from your own AnyTone D168UV package (not part of "
                     "this repo):\n  %s\nsee emu/README.md \"Images\"" % STOCK)
        img = os.path.join(out, "fw.bin"); shutil.copyfile(a.image or STOCK, img)
        load = ["sysbus LoadBinary @%s 0x08004000" % img]
    if a.cfw and not a.systick:
        a.systick = 15000000                         # HCLK/8 as stock FUN_08013c64 and cfw drivers/time.c
    lines = ["include @%s" % os.path.join(HERE, "models", m) for m in MODELS_CS + (CFW_MODELS_CS if a.cfw else STOCK_MODELS_CS)]
    lines += ['mach create "d168uv"',
              "machine LoadPlatformDescription @%s" % make_platform(out, a.systick, a.nand or default_nand(stock=not a.cfw)),
              "logFile @%s" % os.path.join(out, "renode.log"),
              "logLevel 1"] + load
    lines.append('lcd Layout "d168"')                # D168 key matrix (stock and cfw)
    if not a.cfw:
        lines.append("machine LoadPlatformDescription @%s" % os.path.join(HERE, "stock168.repl"))
    if a.cfw:
        ov = open(os.path.join(HERE, "cfw168.repl")).read().replace('"MODELS/', '"%s/' % os.path.join(HERE, "models"))
        open(os.path.join(out, "cfw168.repl"), "w").write(ov)
        lines.append("sysbus Unregister sysbus.timer4")   # cfw TX audio = TMR4 PWM: replaced by models/Pwm168.cs
        lines.append("machine LoadPlatformDescription @%s" % os.path.join(out, "cfw168.repl"))
        if a.elf:
            s_ = elf_syms(a.elf)
            if "g_emu_pcm" in s_ and "g_emu_pcm_wr" in s_:
                lines.append("pcm Attach 0x%08X 0x%08X 8192 @%s" % (s_["g_emu_pcm"], s_["g_emu_pcm_wr"],
                                                                    os.path.join(out, "rx_pcm.raw")))
    for spec in a.uart_socket:
        uart, port = spec.split(":")
        lines.append('emulation CreateServerSocketTerminal %d "%s_sock" false' % (int(port), uart))
        lines.append("connector Connect sysbus.%s %s_sock" % (uart, uart))
    for u in UARTS:
        if any(spec.startswith(u + ":") for spec in a.uart_socket):
            continue
        lines.append("%s CreateFileBackend @%s true" % (u, os.path.join(out, "%s.txt" % u)))
    if a.trace_periph:
        lines.append("sysbus LogAllPeripheralsAccess true")
    hook_rf, hook_delay = 0x0807BCA8, 0x08013D30
    if a.elf:
        # custom firmware (D168UV/cfw): same hooks on its alias symbols (drivers/rf.c, drivers/time.c)
        syms = elf_syms(a.elf)
        hook_rf, hook_delay = syms.get("FUN_0807bca8"), syms.get("FUN_08013d30")
        lines.append("cpu VectorTableOffset 0x%08X" % syms.get("g_vectors", 0x08004000))
        # bootloader stand-in (images/bootstub168.S) at 0x08000000 and the 0x0 alias: a system reset (cfw fault
        # handler) restarts from 0x0 and must land in the app again, as on the radio
        stub = os.path.join(HERE, "images", "bootstub168.bin")
        lines += ["sysbus LoadBinary @%s 0x08000000" % stub, "sysbus LoadBinary @%s 0x00000000" % stub]
    else:
        lines.append("cpu VectorTableOffset 0x08004000")
    if hook_rf:
        # RF chip register read FUN_0807bca8 (SDA turns around; Renode GPIO can't model the shared line):
        # return the model's value directly.
        lines.append('cpu AddHook 0x%08X "from Antmicro.Renode.Peripherals.CPU import RegisterValue; '
                     'from Antmicro.Renode.Core import EmulationManager; '
                     'm = list(EmulationManager.Instance.CurrentEmulation.Machines)[0]; '
                     'r = m[\'sysbus.rf0\']; '
                     'self.SetRegister(0, RegisterValue.Create(r.Peek(int(self.GetRegister(0).RawValue)), 32)); '
                     'self.PC = self.GetRegister(14)"' % (hook_rf & ~1))
        if hook_delay and not a.exact:
            # delay_us FUN_08013d30 polls SysTick: advance virtual time instead.
            # (Large single skips stall the CPU in Renode 1.17: skip in 25 ms slices, re-entering the hook.)
            lines.append('cpu AddHook 0x%08X "from Antmicro.Renode.Time import TimeInterval; '
                         'from Antmicro.Renode.Peripherals.CPU import RegisterValue; '
                         'us = self.GetRegister(0).RawValue; '
                         'self.SkipTime(TimeInterval.FromMicroseconds(min(us, 25000))); '
                         'self.SetRegister(0, RegisterValue.Create(us - min(us, 25000), 32)); '
                         'self.PC = self.GetRegister(14) if us <= 25000 else self.PC"' % (hook_delay & ~1))
    if not a.elf and not a.exact:
        # Idle task 0x0800abe2 spins (OSIdleCtr++ then idle hook 0x08009e42): its call at 0x0800abf8 goes to a cave
        # in the unused gap after ER_IROM1 (0x0801FF00: wfi; b.w 0x08009e42), so the CPU sleeps to the next IRQ.
        lines.append("sysbus LoadBinary @%s 0x0801FF00" % os.path.join(HERE, "images", "idle_cave.bin"))
        lines.append("sysbus LoadBinary @%s 0x0800ABF8" % os.path.join(HERE, "images", "idle_call.bin"))
    if not a.elf and not a.exact:
        # Accelerometer register read/write over bit-banged I2C (FUN_0805aa04 / FUN_0805aaa4, polled all the
        # time): served from the i2c model's register array instead of clocking ~40 GPIO edges per byte.
        lines.append('cpu AddHook 0x0805AA04 "from Antmicro.Renode.Core import EmulationManager; '
                     'm = list(EmulationManager.Instance.CurrentEmulation.Machines)[0]; acc = m[\'sysbus.i2c\'].Accel; '
                     'buf = self.GetRegister(0).RawValue; reg = self.GetRegister(1).RawValue & 0x7F; n = self.GetRegister(2).RawValue; '
                     '[self.Bus.WriteByte(buf + i, acc[(reg + i) & 0xFF]) for i in range(n)]; '
                     'self.PC = self.GetRegister(14)"')
        lines.append('cpu AddHook 0x0805AAA4 "from Antmicro.Renode.Core import EmulationManager; '
                     'm = list(EmulationManager.Instance.CurrentEmulation.Machines)[0]; acc = m[\'sysbus.i2c\'].Accel; '
                     'buf = self.GetRegister(0).RawValue; reg = self.GetRegister(1).RawValue & 0x7F; n = self.GetRegister(2).RawValue; '
                     '[acc.__setitem__((reg + i) & 0xFF, self.Bus.ReadByte(buf + i)) for i in range(n)]; '
                     'self.PC = self.GetRegister(14)"')
    lines += a.extra
    lines.append("include @%s" % os.path.join(HERE, "dump_state.py"))
    if os.path.exists(os.path.join(HERE, "then_cmd.py")):
        lines.append("include @%s" % os.path.join(HERE, "then_cmd.py"))
    have_lcd = "lcd:" in open(os.path.join(HERE, "at32f403a.repl")).read()
    if a.gdb:
        lines.append("machine StartGdbServer %d true" % a.gdb)
    elif a.serve:
        lines.append('emulation RunFor "%s"' % fmt_time(a.seconds))
    else:
        if a.samples:
            for _ in range(a.samples):
                lines.append('emulation RunFor "%s"' % fmt_time(a.seconds / a.samples))
                lines.append('pc_sample "%s"' % os.path.join(out, "pc_samples.txt"))
        else:
            lines.append('emulation RunFor "%s"' % fmt_time(a.seconds))
        shot, cmds = 0, []
        tf, to = os.path.join(out, "then_cmds.txt"), os.path.join(out, "then_out.txt")
        for step in a.then:
            secs, cmd = step.split("|", 1)
            if float(secs) > 0:
                lines.append('emulation RunFor "%s"' % fmt_time(float(secs)))
            if cmd.strip() == "shot":
                shot += 1
                cmd = "lcd Screenshot @%s" % os.path.join(out, "lcd_%02d.ppm" % shot)
            cmds.append(cmd)
            lines.append('then_cmd "%s" %d "%s"' % (tf, len(cmds) - 1, to))
        open(tf, "w").write("\n".join(cmds) + "\n")
        lines.append('dump_state "%s"' % os.path.join(out, "state.txt"))
        if have_lcd:
            lines.append("lcd Screenshot @%s" % os.path.join(out, "lcd.ppm"))
        lines.append("quit")
    resc = os.path.join(out, "run.resc")
    open(resc, "w").write("\n".join(lines) + "\n")
    os.environ["D168_OUT_DIR"] = out
    os.environ["D168_BB_LOG"] = os.path.join(out, "baseband.log")
    if os.path.exists(os.environ["D168_BB_LOG"]):
        os.remove(os.environ["D168_BB_LOG"])
    cmd = [RENODE, "--disable-gui", "--plain", resc]
    if a.serve:
        log = open(os.path.join(out, "console.txt"), "w")
        p = subprocess.Popen(cmd + ["-P", str(a.serve)], cwd=HERE, stdout=log, stderr=subprocess.STDOUT,
                             stdin=subprocess.DEVNULL, start_new_session=True)
        open(os.path.join(out, "renode.pid"), "w").write(str(p.pid))
        time.sleep(3)
        subprocess.Popen([sys.executable, os.path.join(HERE, "ctl.py"), "--port", str(a.serve), "broker"], cwd=HERE,
                         stdout=open(os.path.join(out, "broker.txt"), "w"), stderr=subprocess.STDOUT,
                         stdin=subprocess.DEVNULL, start_new_session=True)
        print("Renode pid %d, monitor :%d, out %s" % (p.pid, a.serve, out))
        return 0
    if a.gdb:
        return subprocess.call(cmd + ["-P", "1334"])
    t0 = time.time()
    try:
        p = subprocess.run(cmd + ["-P", "-1"], cwd=HERE, capture_output=True, text=True, timeout=a.timeout)
        console = p.stdout + p.stderr
    except subprocess.TimeoutExpired as e:
        console = "HOST TIMEOUT after %ds" % a.timeout
    open(os.path.join(out, "console.txt"), "w").write(console)
    st = os.path.join(out, "state.txt")
    state = open(st).read() if os.path.exists(st) else ""
    print("== %s: %.1f virtual s in %.0f host s" % (name, a.seconds, time.time() - t0))
    print(state.strip() or "(no state: see %s/console.txt)" % out)
    for ppm in sorted(glob.glob(os.path.join(out, "*.ppm"))):
        subprocess.call([sys.executable, "-I", os.path.join(HERE, "ppm2png.py"), ppm, ppm[:-4] + ".png"])
    if os.path.exists(os.path.join(out, "lcd.png")):
        print("-- screen: %s" % os.path.join(out, "lcd.png"))
    to = os.path.join(out, "then_out.txt")
    if a.then and os.path.exists(to):
        print(open(to).read().rstrip())
    for u in UARTS:
        f = os.path.join(out, "%s.txt" % u)
        if os.path.exists(f) and os.path.getsize(f):
            print("-- %s (%d bytes): %r" % (u, os.path.getsize(f), open(f, "rb").read(200)))
    return 3 if "HOST TIMEOUT" in console else (2 if re.search(r"halted=True|HardFault", state) else 0)


if __name__ == "__main__":
    sys.exit(main())
